import assert from 'node:assert/strict'
import { existsSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { chromium } from 'playwright-core'

const candidates = process.platform === 'win32'
  ? ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe']
  : process.platform === 'darwin'
    ? ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome']
    : ['/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser']
const executablePath = process.env.CHROME_PATH || candidates.find(existsSync)
if (!executablePath) throw new Error('Set CHROME_PATH to an installed Chromium-compatible browser.')
const baseURL = process.env.PAPERFLOW_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({ executablePath, headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })

try {
  await page.goto(baseURL, { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: '你好，研究者 ✳' }).waitFor()
  assert.equal(await page.getByText('以下论文、进度和团队动态均为演示数据。', { exact: false }).count(), 1)
  await page.screenshot({ path: path.join(os.tmpdir(), 'paperflow-dashboard.png'), fullPage: true })
  await page.getByRole('button', { name: '收起导航栏' }).click()
  assert.equal(await page.getByRole('button', { name: '展开导航栏' }).count(), 1)
  await page.getByRole('button', { name: '展开导航栏' }).click()
  const search = page.getByRole('textbox', { name: '搜索演示文献' })
  await search.fill('not a real paper')
  assert.equal(await page.getByText('没有找到演示文献').count(), 1)
  await search.fill('BERT')
  assert.equal(await page.locator('.paper-row').count(), 1)
  await search.fill('')
  await page.getByRole('link', { name: '打开 PDF 验证示例', exact: true }).click()
  await page.locator('.textLayer span', { hasText: 'Research grows through small' }).waitFor({ state: 'attached', timeout: 30000 })
  await page.getByRole('button', { name: '下一页' }).waitFor({ state: 'visible' })
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.page-counter').innerText(), '1 / 2')
  const firstCanvas = await page.locator('.pdf-page canvas').evaluate(canvas => ({ width: canvas.width, height: canvas.height }))
  assert.ok(firstCanvas.width > 0 && firstCanvas.height > 0)
  await page.screenshot({ path: path.join(os.tmpdir(), 'paperflow-pdf.png'), fullPage: true })

  const firstLine = page.locator('.textLayer span', { hasText: 'Research grows through small' }).first()
  const box = await firstLine.boundingBox()
  assert.ok(box && box.width > 20 && box.height > 5, 'PDF text layer has visible geometry')
  await firstLine.scrollIntoViewIfNeeded()
  const visibleBox = await firstLine.boundingBox()
  await page.mouse.move(visibleBox.x + 2, visibleBox.y + visibleBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(visibleBox.x + visibleBox.width * 0.8, visibleBox.y + visibleBox.height / 2, { steps: 12 })
  await page.mouse.up()
  await page.getByRole('button', { name: '保存高亮' }).waitFor()
  assert.match(await page.locator('.selection-box').innerText(), /第 1 页/)
  const selectedText = await page.locator('.selection-box p').innerText()
  assert.ok(selectedText.length > 10)
  await page.getByRole('button', { name: '保存高亮' }).click()
  assert.equal(await page.locator('.pdf-highlight').count(), 1)
  const initial = await page.locator('.pdf-highlight').evaluate(element => ({ left: element.style.left, top: element.style.top, width: element.style.width, height: element.style.height }))
  async function assertHighlightAlignment(text) {
    const positions = await page.evaluate((text) => {
      const span = [...document.querySelectorAll('.textLayer span')].find(element => element.textContent?.includes(text))
      if (!span?.firstChild) return null
      const offset = span.textContent.indexOf(text)
      const range = document.createRange()
      range.setStart(span.firstChild, offset)
      range.setEnd(span.firstChild, offset + text.length)
      const expected = range.getBoundingClientRect()
      const actual = document.querySelector('.pdf-highlight')?.getBoundingClientRect()
      return actual && { dx: Math.abs(expected.x - actual.x), dy: Math.abs(expected.y - actual.y), dw: Math.abs(expected.width - actual.width), dh: Math.abs(expected.height - actual.height), expectedWidth: expected.width, actualWidth: actual.width, text, scale: getComputedStyle(span).transform, font: getComputedStyle(span).fontFamily, fontSize: getComputedStyle(span).fontSize, fontWeight: getComputedStyle(span).fontWeight, letterSpacing: getComputedStyle(span).letterSpacing, spanWidth: span.getBoundingClientRect().width, pageWidth: document.querySelector('.pdf-page').getBoundingClientRect().width, canvases: [...document.querySelectorAll('canvas')].map(x => ({ cls: x.className, width: x.width, height: x.height })) }
    }, text)
    assert.ok(positions && positions.dx < 3 && positions.dy < 3 && positions.dw < 3 && positions.dh < 3, `Highlight alignment: ${JSON.stringify(positions)}`)
  }
  await assertHighlightAlignment(selectedText)
  const saved = await page.evaluate(() => Object.entries(localStorage).filter(([key]) => key.startsWith('paperflow:pdf-anchors:v1:')).map(([, value]) => JSON.parse(value)))
  assert.equal(saved.length, 1)
  assert.equal(saved[0][0].page, 1)
  assert.equal(saved[0][0].text, selectedText)
  assert.ok(saved[0][0].rects[0].x > 0 && saved[0][0].rects[0].width > 0)
  await page.getByRole('button', { name: '放大' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.zoom-label').innerText(), '120%')
  assert.deepEqual(await page.locator('.pdf-highlight').evaluate(element => ({ left: element.style.left, top: element.style.top, width: element.style.width, height: element.style.height })), initial)
  await assertHighlightAlignment(selectedText)
  await page.getByRole('button', { name: '重新渲染页面' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.pdf-highlight').count(), 1)
  await page.getByRole('button', { name: '下一页' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.page-counter').innerText(), '2 / 2')
  assert.equal(await page.locator('.pdf-highlight').count(), 0)
  await page.getByRole('button', { name: '上一页' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.pdf-highlight').count(), 1)
  await page.reload({ waitUntil: 'networkidle' })
  await page.locator('.pdf-highlight').waitFor({ timeout: 30000 })
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.deepEqual(await page.locator('.pdf-highlight').evaluate(element => ({ left: element.style.left, top: element.style.top, width: element.style.width, height: element.style.height })), initial)
  assert.match(await page.locator('.saved-item__text').innerText(), /第 1 页/)
  await assertHighlightAlignment(selectedText)
  await page.getByRole('button', { name: '删除高亮' }).click()
  assert.equal(await page.locator('.pdf-highlight').count(), 0)

  const multilineStart = page.locator('.textLayer span', { hasText: 'Research grows through small' }).first()
  const multilineEnd = page.locator('.textLayer span', { hasText: 'underline a sentence, write a note' }).first()
  await multilineStart.scrollIntoViewIfNeeded()
  const startBox = await multilineStart.boundingBox()
  const endBox = await multilineEnd.boundingBox()
  assert.ok(startBox && endBox)
  await page.mouse.move(startBox.x + 2, startBox.y + startBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(endBox.x + endBox.width * 0.7, endBox.y + endBox.height / 2, { steps: 15 })
  await page.mouse.up()
  await page.getByRole('button', { name: '保存高亮' }).waitFor()
  await page.getByRole('button', { name: '保存高亮' }).click()
  assert.ok(await page.locator('.pdf-highlight').count() >= 2, 'Multiline selection should have multiple rectangles')
  const multilineCount = await page.locator('.pdf-highlight').count()
  await page.getByRole('button', { name: '放大' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.pdf-highlight').count(), multilineCount)
  await page.reload({ waitUntil: 'networkidle' })
  await page.locator('.pdf-highlight').first().waitFor()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.pdf-highlight').count(), multilineCount)
  await page.getByRole('button', { name: '删除高亮' }).click()

  await page.getByRole('button', { name: '下一页' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  const secondPageLine = page.locator('.textLayer span', { hasText: 'Research is rarely a straight line.' }).first()
  await secondPageLine.scrollIntoViewIfNeeded()
  const secondBox = await secondPageLine.boundingBox()
  assert.ok(secondBox)
  await page.mouse.move(secondBox.x + 2, secondBox.y + secondBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(secondBox.x + secondBox.width * 0.8, secondBox.y + secondBox.height / 2, { steps: 10 })
  await page.mouse.up()
  await page.getByRole('button', { name: '保存高亮' }).waitFor()
  assert.match(await page.locator('.selection-box').innerText(), /第 2 页/)
  await page.getByRole('button', { name: '保存高亮' }).click()
  await page.getByRole('button', { name: '上一页' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.pdf-highlight').count(), 0)
  await page.getByRole('button', { name: '下一页' }).click()
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  assert.equal(await page.locator('.pdf-highlight').count(), 1)
  await page.getByRole('button', { name: '删除高亮' }).click()
  await page.locator('input[type=file]').setInputFiles(path.resolve('package.json'))
  assert.equal(await page.getByRole('alert').filter({ hasText: '请选择不超过 20 MB' }).count(), 1)
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('input[type=file]').setInputFiles(path.resolve('public/paperflow-sample.pdf'))
  await page.getByText('本地文件：paperflow-sample.pdf', { exact: false }).waitFor()
  await page.locator('.textLayer span', { hasText: 'Research grows through small' }).waitFor({ state: 'attached', timeout: 30000 })
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  await page.locator('input[type=file]').setInputFiles({ name: 'broken.pdf', mimeType: 'application/pdf', buffer: Buffer.from('not a PDF') })
  await page.getByRole('alert').filter({ hasText: '无法打开 PDF' }).waitFor()
  assert.equal(await page.locator('.pdf-rendering').count(), 0)
  await page.getByRole('button', { name: '使用示例' }).click()
  await page.getByText('原创双页示例文档', { exact: false }).waitFor()
  await page.locator('.textLayer span', { hasText: 'Research grows through small' }).waitFor({ state: 'attached', timeout: 30000 })
  await page.goto(`${baseURL}/library`)
  await page.getByRole('heading', { name: '个人文献库' }).waitFor()
  await page.getByText('还没有文献').waitFor()
  await page.goto(`${baseURL}/knowledge`)
  await page.getByText('科研知识库需要远程模式').waitFor()
  await page.goto(`${baseURL}/team`)
  await page.getByText('团队空间需要远程模式').waitFor()
  assert.deepEqual(errors, [])
  console.log('Desktop: dashboard, navigation, search, empty state, placeholders and local file validation passed.')
  console.log('PDF: render, text drag selection, page/geometry capture, save, zoom, rerender, paging, refresh restore, delete and local PDF passed.')

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true })
  const mobilePage = await mobile.newPage()
  const mobileErrors = []
  mobilePage.on('pageerror', error => mobileErrors.push(error.message))
  mobilePage.on('console', message => { if (message.type() === 'error') mobileErrors.push(message.text()) })
  await mobilePage.goto(baseURL, { waitUntil: 'networkidle' })
  await mobilePage.getByRole('button', { name: '打开导航' }).click()
  assert.equal(await mobilePage.getByRole('link', { name: '团队空间', exact: true }).isVisible(), true)
  await mobilePage.locator('.sidebar-close').click()
  await mobilePage.screenshot({ path: path.join(os.tmpdir(), 'paperflow-mobile.png'), fullPage: true, animations: 'disabled' })
  const overflow = await mobilePage.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
  assert.equal(overflow.scroll, overflow.width)
  await mobilePage.getByRole('link', { name: '打开 PDF 验证示例', exact: true }).click()
  await mobilePage.locator('.textLayer span', { hasText: 'Research grows through small' }).waitFor({ state: 'attached', timeout: 30000 })
  assert.equal(await mobilePage.locator('.page-counter').innerText(), '1 / 2')
  const pdfOverflow = await mobilePage.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
  assert.equal(pdfOverflow.scroll, pdfOverflow.width)
  assert.deepEqual(mobileErrors, [])
  await mobile.close()
  console.log('Mobile: responsive dashboard, navigation and PDF rendering passed.')
  console.log(`Screenshots: ${path.join(os.tmpdir(), 'paperflow-dashboard.png')}, ${path.join(os.tmpdir(), 'paperflow-pdf.png')}, ${path.join(os.tmpdir(), 'paperflow-mobile.png')}`)
} finally {
  await browser.close()
}
