import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { chromium } from 'playwright-core'

const candidates = process.platform === 'win32' ? ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'] : process.platform === 'darwin' ? ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'] : ['/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser']
const executablePath = process.env.CHROME_PATH || candidates.find(existsSync)
if (!executablePath) throw new Error('Set CHROME_PATH to an installed Chromium-compatible browser.')
const baseURL = process.env.PAPERFLOW_URL
if (!baseURL) throw new Error('Set PAPERFLOW_URL to an isolated test server; this test creates accounts and uploads files.')
const suffix = randomUUID()
const emailA = `a-${suffix}@example.test`
const emailB = `b-${suffix}@example.test`
const password = 'Browser-password-123'
const browser = await chromium.launch({ executablePath, headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  const input = page.locator('input[type=file]')
  const sample = path.resolve('public/paperflow-sample.pdf')
  await page.goto(`${baseURL}/library`, { waitUntil: 'networkidle' })
  await input.setInputFiles(sample)
  await page.getByRole('status').filter({ hasText: '已保存到本地文献库' }).waitFor({ timeout: 30000 })
  await page.getByRole('combobox', { name: '存储模式' }).selectOption('remote')
  await page.getByRole('heading', { name: '登录远程文献库' }).waitFor()
  await page.getByRole('button', { name: '没有账号？注册' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill('浏览器甲')
  await page.getByRole('textbox', { name: '邮箱' }).fill(emailA)
  await page.getByLabel('密码').fill(password)
  await page.getByRole('button', { name: '注册并登录' }).click()
  await page.getByText('还没有文献').waitFor()
  await input.setInputFiles(sample)
  await page.getByRole('status').filter({ hasText: '已保存到远程文献库' }).waitFor({ timeout: 30000 })
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('link', { name: 'paperflow-sample', exact: true }).waitFor()
  await page.getByRole('link', { name: '开始阅读' }).click()
  await page.locator('.textLayer span', { hasText: 'Research grows through small' }).waitFor({ state: 'attached', timeout: 30000 })
  await page.waitForFunction(() => !document.querySelector('.pdf-rendering'))
  const remotePaper = page.url()
  const line = page.locator('.textLayer span', { hasText: 'Research grows through small' }).first()
  await line.scrollIntoViewIfNeeded()
  const box = await line.boundingBox()
  assert.ok(box)
  await page.mouse.move(box.x + 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.8, box.y + box.height / 2, { steps: 12 })
  await page.mouse.up()
  await page.getByRole('button', { name: '保存高亮' }).click()
  await page.getByRole('status').filter({ hasText: '高亮已保存' }).waitFor()
  await page.locator('.reader-highlight').first().click()
  await page.getByRole('textbox', { name: '高亮笔记' }).fill('远程阅读笔记持久化')
  await page.getByRole('button', { name: '保存笔记' }).click()
  await page.getByRole('status').filter({ hasText: '笔记已保存' }).waitFor()
  await page.getByRole('button', { name: '下一页' }).click()
  await page.waitForFunction(() => document.querySelector('.page-counter')?.textContent?.replace(/\s/g, '') === '2/2' && !document.querySelector('.pdf-rendering'))
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => document.querySelector('.page-counter')?.textContent?.replace(/\s/g, '') === '2/2' && !document.querySelector('.pdf-rendering'))
  await page.getByRole('button', { name: '上一页' }).click()
  await page.locator('.reader-highlight').first().waitFor()
  await page.locator('.reader-highlight').first().click()
  await page.waitForFunction(() => document.querySelector('textarea[aria-label="高亮笔记"]')?.value === '远程阅读笔记持久化')
  await page.getByRole('link', { name: /账号资料/ }).click()
  await page.getByRole('textbox', { name: '名称' }).fill('浏览器甲更新')
  await page.getByRole('button', { name: '保存资料' }).click()
  await page.getByRole('status').filter({ hasText: '账号资料已保存' }).waitFor()
  await page.goto(`${baseURL}/library`)
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByRole('button', { name: '没有账号？注册' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill('浏览器乙')
  await page.getByRole('textbox', { name: '邮箱' }).fill(emailB)
  await page.getByLabel('密码').fill(password)
  await page.getByRole('button', { name: '注册并登录' }).click()
  await page.getByText('还没有文献').waitFor()
  await page.goto(remotePaper)
  await page.getByRole('alert').filter({ hasText: '无法打开 PDF' }).waitFor()
  await page.goto(`${baseURL}/library`)
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByRole('textbox', { name: '邮箱' }).fill(emailA)
  await page.getByLabel('密码').fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: 'paperflow-sample', exact: true }).waitFor()
  await page.getByRole('combobox', { name: '存储模式' }).selectOption('local')
  await page.getByRole('link', { name: 'paperflow-sample', exact: true }).waitFor()
  assert.equal(await page.locator('.library-row').count(), 1)
  await page.getByRole('combobox', { name: '存储模式' }).selectOption('remote')
  await page.getByRole('link', { name: 'paperflow-sample', exact: true }).waitFor()
  assert.equal(await page.locator('.library-row').count(), 1)
  assert.deepEqual(errors, [])
  console.log('真实浏览器：远程注册登录、模式隔离、上传、阅读、高亮、笔记、进度、刷新、退出重登及越权拒绝通过。')
} finally {
  await browser.close()
}
